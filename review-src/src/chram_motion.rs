pub fn section(class: &str, property: &str) -> Option<&'static str> {
    Some(match (class, property) {
        ("priest", "image_die") => "sl_anim_priest_die",
        ("priest", "image_spell" | "image_reaction") => "sl_anim_priest_cast",
        ("priest", "image_attack") => "sl_anim_priest_attack",
        ("priest", "image") => "sl_anim_priest_walk",
        ("priest", "image_idle") => "sl_anim_priest_idle",
        ("mage", "image_idle") => "sl_anim_mage_idle",
        ("mage", "image") => "sl_anim_mage_walk",
        ("mage", "image_attack" | "image_spell") => "sl_anim_mage_attack",
        ("mage", "image_die") => "sl_anim_mage_die",
        ("leszy", "image_idle") => "sl_anim_leszy_idle",
        ("leszy", "image") => "sl_anim_leszy_walk",
        ("leszy", "image_spell") => "sl_anim_leszy_roots",
        ("leszy", "image_attack") => "sl_anim_leszy_attack",
        ("leszy", "image_die") => "sl_anim_leszy_die",
        ("wolf", "image_idle") => "sl_anim_wolf_idle",
        ("wolf", "image") => "sl_anim_wolf_walk",
        ("wolf", "image_attack") => "sl_anim_wolf_attack",
        ("wolf", "image_die") => "sl_anim_wolf_die",
        ("boar", "image_idle") => "sl_anim_boar_idle",
        ("boar", "image") => "sl_anim_boar_walk",
        ("boar", "image_attack") => "sl_anim_boar_attack",
        ("boar", "image_die") => "sl_anim_boar_die",
        ("raven", "image_idle") => "sl_anim_raven_idle",
        ("raven", "image") => "sl_anim_raven_walk",
        ("raven", "image_attack" | "image_spell") => "sl_anim_raven_attack",
        ("raven", "image_die") => "sl_anim_raven_die",
        _ => return None,
    })
}
